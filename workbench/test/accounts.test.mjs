test('旧数据迁移备份，账号注册表重开保留各账号独立状态',async t=>{
 const dir=await fs.mkdtemp(path.join(os.tmpdir(),'xhs-account-store-'));
 t.after(()=>fs.rm(dir,{recursive:true,force:true}));
 const legacy={settings:{endpoint:'http://127.0.0.1:1/mcp',monitorMinutes:0},drafts:[{id:'old',title:'旧草稿'}],snapshots:[],history:[],submissions:{x:{date:'2030-01-01',status:'uncertain'}},assets:{},login:{status:'logged_in',name:'旧账号',profile:{redId:'old-id'}}};
 await fs.writeFile(path.join(dir,'state.json'),JSON.stringify(legacy));
 const store=await AccountStore.open(dir,legacy.settings.endpoint);
 const a=store.items[0];
 assert.equal(a.state.drafts[0].title,'旧草稿');assert.equal(a.state.submissions.x.status,'uncertain');
 assert.ok((await fs.readdir(dir)).some(n=>n.startsWith('state-before-multi-')));
 const b=await store.add('第二账号');
 b.state.login={status:'logged_in',name:'第二账号'};
 b.state.snapshots.push({at:'2026-10-08T00:00:00Z',profile:{nickname:'未核实'},notes:[]});
 assert.equal(store.list().find(x=>x.id===b.id).lastCollectedAt,undefined,'缺少账号标识时不关联采集记录');
 store.selectedAccountId=b.id;await store.save();
 const again=await AccountStore.open(dir,legacy.settings.endpoint);
 assert.equal(again.items.length,2);assert.equal(again.selectedAccountId,b.id);
 assert.equal(again.get(a.id).state.login.name,'旧账号');assert.equal(again.get(b.id).state.login.name,'第二账号');
 assert.equal(again.get(b.id).state.drafts.length,0);
});

